"""Synthetic market data for tests that can't reach the BYU data store.

:func:`synthetic_market` draws returns from its own Barra-shaped risk model,
using real Barra factor names (country, a few 0/1 industries, and styles) so
factor-set constants work unchanged. Two optional effects can be planted:

- ``planted_ic``: specific returns over each block of ``horizon`` days are
  predicted by a score known at the close before the block, with this IC.
- ``industry_drift``: industry factor returns have a persistent drift that is
  redrawn every half year, so trailing industry returns predict future ones.
"""

from __future__ import annotations

import datetime as dt

import numpy as np
import polars as pl

from sf_quant.data.covariance_matrix import RiskModel

INDUSTRIES = ["USSLOWL_BANKS", "USSLOWL_OILGSEXP", "USSLOWL_PHARMA", "USSLOWL_SOFTWARE"]
STYLES = ["USSLOWL_BETA", "USSLOWL_MOMENTUM", "USSLOWL_SIZE"]
FACTORS = ["USSLOWL_COUNTRY", *INDUSTRIES, *STYLES]


class PanelMarketData:
    """:class:`~sf_quant.data.market.MarketData` over in-memory panels with one static risk model."""

    def __init__(
        self,
        returns: pl.DataFrame,  # date, barrid, return
        benchmark: pl.DataFrame,  # date, barrid, weight
        ids: list[str],
        factor_exposures: np.ndarray,
        factor_covariance: np.ndarray,
        specific_variance: np.ndarray,
        factor_names: list[str],
        factor_returns: pl.DataFrame | None = None,  # date + factor columns; zeros if omitted
        specific_returns: pl.DataFrame | None = None,  # date, barrid, specific_return; = returns if omitted
        prices: pl.DataFrame | None = None,  # date, barrid, price; $50 if omitted
    ) -> None:
        days = benchmark["date"].unique().sort()
        self.days = days.to_list()
        self.ids = ids
        self.B, self.F, self.delta = factor_exposures, factor_covariance, specific_variance
        self.factor_names = factor_names
        self.returns = returns
        self.benchmark = benchmark
        self.factors = (
            factor_returns
            if factor_returns is not None
            else pl.DataFrame({"date": days} | {f: np.zeros(len(days)) for f in factor_names})
        )
        self.specific = (
            specific_returns if specific_returns is not None else returns.rename({"return": "specific_return"})
        )
        self.price_panel = prices if prices is not None else benchmark.select("date", "barrid", price=pl.lit(50.0))
        self.missing_risk: set[str] = set()
        self.planted_scores: pl.DataFrame | None = None

    def benchmark_weights(self, start, end):
        return self.benchmark.filter(pl.col("date").is_between(start, end))

    def asset_returns(self, start, end, barrids):
        return self.returns.filter(pl.col("date").is_between(start, end), pl.col("barrid").is_in(barrids))

    def specific_returns(self, start, end, barrids):
        return self.specific.filter(pl.col("date").is_between(start, end), pl.col("barrid").is_in(barrids))

    def factor_returns(self, start, end):
        return self.factors.filter(pl.col("date").is_between(start, end))

    def exposures(self, date_, barrids):
        index = {b: i for i, b in enumerate(self.ids)}
        rows = [index[b] for b in barrids]
        return pl.DataFrame({"barrid": barrids} | {f: self.B[rows, k] for k, f in enumerate(self.factor_names)})

    def prices(self, start, end):
        return self.price_panel.filter(pl.col("date").is_between(start, end))

    def risk_model(self, date_, barrids):
        index = {b: i for i, b in enumerate(self.ids)}
        present = [b for b in barrids if b in index and b not in self.missing_risk]
        rows = [index[b] for b in present]
        return RiskModel(
            ids=present,
            factor_exposures=self.B[rows],
            factor_covariance=self.F,
            specific_variance=self.delta[rows],
            factor_names=list(self.factor_names),
            missing_ids=sorted(set(barrids) - set(present)),
        )


def business_days(start: dt.date, n: int) -> list[dt.date]:
    days, d = [], start
    while len(days) < n:
        if d.weekday() < 5:
            days.append(d)
        d += dt.timedelta(days=1)
    return days


def synthetic_market(
    n_assets: int = 200,
    n_days: int = 756,
    start: dt.date = dt.date(2010, 1, 4),
    seed: int = 0,
    planted_ic: float = 0.0,
    industry_drift: float = 0.0,
    horizon: int = 21,
) -> PanelMarketData:
    """
    A market generated by its own risk model, so realized TE should match the target.

    The country factor (exposure 1) has about 16% annual volatility; each
    asset belongs to one of four industries. Daily returns are B f + u. The
    benchmark is cap-weighted with caps drifting with returns. See the module
    docstring for the planted effects; the planted scores are stored on
    ``planted_scores`` (date, barrid, score).
    """
    rng = np.random.default_rng(seed)
    ids = [f"S{i:04d}" for i in range(n_assets)]
    n_ind = len(INDUSTRIES)

    B = np.zeros((n_assets, len(FACTORS)))
    B[:, 0] = 1.0
    B[np.arange(n_assets), 1 + rng.integers(0, n_ind, n_assets)] = 1.0
    B[:, 1 + n_ind :] = rng.normal(0, 1, (n_assets, len(STYLES)))
    F = np.diag([0.16**2] + [0.05**2] * n_ind + [0.04**2] * len(STYLES))
    delta = rng.uniform(0.20, 0.45, n_assets) ** 2
    sigma = np.sqrt(delta)

    days = business_days(start, n_days)
    f = rng.multivariate_normal(np.zeros(len(FACTORS)), F / 252, n_days)
    if industry_drift:
        regimes = rng.normal(0, 1, (n_days // 126 + 1, n_ind))
        f[:, 1 : 1 + n_ind] += industry_drift / 252 * regimes[np.arange(n_days) // 126]

    # Planted stock-level effect: per-day loading a gives the planted IC over a block of `horizon` days.
    a = np.sqrt(planted_ic**2 / (horizon - planted_ic**2 * (horizon - 1))) if planted_ic else 0.0
    blocks = rng.normal(0, 1, (n_days // horizon + 2, n_assets))
    block = np.arange(n_days) // horizon
    noise = rng.normal(0, 1, (n_days, n_assets))
    u = sigma / np.sqrt(252) * (a * blocks[block] + np.sqrt(1 - a**2) * noise)

    r = f @ B.T + u
    caps = rng.lognormal(0, 1.0, n_assets) * np.cumprod(1 + r, axis=0)

    def panel(values, column):
        return pl.DataFrame({"date": [d for d in days for _ in ids], "barrid": ids * n_days, column: values.ravel()})

    md = PanelMarketData(
        returns=panel(r, "return"),
        benchmark=panel(caps / caps.sum(axis=1, keepdims=True), "weight"),
        prices=panel(50 * np.cumprod(1 + r, axis=0), "price"),
        specific_returns=panel(u, "specific_return"),
        ids=ids,
        factor_exposures=B,
        factor_covariance=F,
        specific_variance=delta,
        factor_names=list(FACTORS),
        factor_returns=pl.DataFrame({"date": days} | {n: f[:, k] for k, n in enumerate(FACTORS)}),
    )
    # The score known at the close of day d predicts the block containing day d + 1.
    md.planted_scores = panel(
        blocks[np.minimum(block + (np.arange(n_days) % horizon == horizon - 1), block.max() + 1)], "score"
    )
    return md
